/// Convert a view scalar expression to its owned equivalent.
fn view_to_owned_conv(var: &str, ft: FieldType) -> String {
    match ft {
        FieldType::String => format!("{var}.to_string()"),
        FieldType::Bytes => format!("{var}.to_vec()"),
        FieldType::Message => format!("{var}.into()"),
        FieldType::Enum => var.to_string(), // EnumValue<E> is Copy
        _ => var.to_string(), // scalars are Copy
    }
}

/// Convert a view scalar value to owned (for map keys and bare fields).
fn view_to_owned_scalar_conv(var: &str, ft: FieldType) -> String {
    match ft {
        FieldType::String => format!("{var}.to_string()"),
        FieldType::Bytes => format!("{var}.to_vec()"),
        _ => var.to_string(),
    }
}

/// Convert an Option<view_type> to Option<owned_type> for optional fields.
fn view_to_owned_option_conv(field_name: &str, ft: FieldType) -> String {
    match ft {
        FieldType::String => format!("view.{field_name}.map(|v| v.to_string())"),
        FieldType::Bytes => format!("view.{field_name}.map(|v| v.to_vec())"),
        _ => format!("view.{field_name}"), // scalars/enums are Copy inside Option
    }
}

/// Compute the total content size of a packed repeated field (without tag/length prefix).
/// Returns the decode function path for an extension field's scalar type.
fn extension_decode_fn_name(ft: FieldType) -> &'static str {
    match ft {
        FieldType::Int32 => "|buf| { let (v, c) = protoc_rs_runtime::wire::decode_varint(buf)?; ::core::result::Result::Ok((v as i32, c)) }",
        FieldType::Int64 => "|buf| { let (v, c) = protoc_rs_runtime::wire::decode_varint(buf)?; ::core::result::Result::Ok((v as i64, c)) }",
        FieldType::Uint32 => "|buf| { let (v, c) = protoc_rs_runtime::wire::decode_varint(buf)?; ::core::result::Result::Ok((v as u32, c)) }",
        FieldType::Uint64 => "|buf| { let (v, c) = protoc_rs_runtime::wire::decode_varint(buf)?; ::core::result::Result::Ok((v, c)) }",
        FieldType::Bool => "|buf| { let (v, c) = protoc_rs_runtime::wire::decode_varint(buf)?; ::core::result::Result::Ok((v != 0, c)) }",
        FieldType::Fixed32 => "|buf| protoc_rs_runtime::wire::decode_fixed32(buf)",
        FieldType::Fixed64 => "|buf| protoc_rs_runtime::wire::decode_fixed64(buf)",
        FieldType::Sfixed32 => "|buf| { let (v, c) = protoc_rs_runtime::wire::decode_fixed32(buf)?; ::core::result::Result::Ok((v as i32, c)) }",
        FieldType::Sfixed64 => "|buf| { let (v, c) = protoc_rs_runtime::wire::decode_fixed64(buf)?; ::core::result::Result::Ok((v as i64, c)) }",
        FieldType::Float => "|buf| { let (v, c) = protoc_rs_runtime::wire::decode_fixed32(buf)?; ::core::result::Result::Ok((f32::from_bits(v), c)) }",
        FieldType::Double => "|buf| { let (v, c) = protoc_rs_runtime::wire::decode_fixed64(buf)?; ::core::result::Result::Ok((f64::from_bits(v), c)) }",
        FieldType::Sint32 => "|buf| { let (v, c) = protoc_rs_runtime::wire::decode_varint(buf)?; ::core::result::Result::Ok((protoc_rs_runtime::wire::zigzag_decode_32(v as u32), c)) }",
        FieldType::Sint64 => "|buf| { let (v, c) = protoc_rs_runtime::wire::decode_varint(buf)?; ::core::result::Result::Ok((protoc_rs_runtime::wire::zigzag_decode_64(v), c)) }",
        _ => "|buf| { let (v, c) = protoc_rs_runtime::wire::decode_varint(buf)?; ::core::result::Result::Ok((v as i32, c)) }",
    }
}

