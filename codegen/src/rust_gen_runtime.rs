    fn gen_extension(
        &mut self,
        field: &FieldDescriptorProto,
    ) -> Result<(), CodeGenError> {
        let name = field
            .name
            .as_deref()
            .ok_or(CodeGenError::MissingFieldName)?;
        let rust_name = to_snake(name).to_uppercase();
        let field_number = field.number.unwrap_or(0) as u32;
        let field_type = field.r#type.unwrap_or(FieldType::Int32);
        let extendee = field.extendee.as_deref().unwrap_or("Unknown");
        let extendee_rust = fqn_to_rust_path(extendee, &self.current_fqn_prefix());

        if field_type == FieldType::Message {
            let msg_type = self.rust_field_type_runtime(field);
            self.push_line(&format!(
                "/// Extension field `{name}` (field {field_number}) for `{extendee}`."
            ));
            self.push_line(&format!(
                "pub static {rust_name}: protoc_rs_runtime::extension::MessageExtensionDescriptor<{msg_type}> = protoc_rs_runtime::extension::MessageExtensionDescriptor {{"
            ));
            self.indent += 1;
            self.push_line(&format!("field_number: {field_number},"));
            self.push_line(&format!(
                "decode_fn: |buf| protoc_rs_runtime::decode(buf),"
            ));
            self.indent -= 1;
            self.push_line("};");
        } else {
            let wt = wire_type_enum_for_field_type(field_type);
            let rust_type = rust_scalar_type(field_type);
            let decode_fn = extension_decode_fn_name(field_type);
            let default = self.field_default_value_scalar(field_type);

            self.push_line(&format!(
                "/// Extension field `{name}` (field {field_number}) for `{extendee}`."
            ));
            self.push_line(&format!(
                "pub static {rust_name}: protoc_rs_runtime::extension::ExtensionDescriptor<{rust_type}> = protoc_rs_runtime::extension::ExtensionDescriptor {{"
            ));
            self.indent += 1;
            self.push_line(&format!("field_number: {field_number},"));
            self.push_line(&format!("wire_type: {wt},"));
            self.push_line(&format!("decode_fn: {decode_fn},"));
            self.push_line(&format!("default_value: {default},"));
            self.indent -= 1;
            self.push_line("};");
        }

        Ok(())
    }

    fn field_default_value_scalar(&self, ft: FieldType) -> String {
        match ft {
            FieldType::Bool => "false".to_string(),
            FieldType::Float | FieldType::Double => "0.0".to_string(),
            FieldType::String => "::std::string::String::new()".to_string(),
            FieldType::Bytes => "::std::vec::Vec::new()".to_string(),
            _ => "0".to_string(),
        }
    }

    fn gen_struct_field(
        &mut self,
        field: &FieldDescriptorProto,
        parent_msg: &DescriptorProto,
    ) -> Result<(), CodeGenError> {
        let name = field
            .name
            .as_deref()
            .ok_or(CodeGenError::MissingFieldName)?;
        let rust_name = to_snake(name);
        let label = field.label.unwrap_or(FieldLabel::Optional);

        // Map field
        if let Some((key_field, val_field)) = find_map_entry(field, parent_msg) {
            let key_type = rust_scalar_type(key_field.r#type.unwrap_or(FieldType::Int32));
            let val_type = self.rust_field_type_runtime(val_field);
            self.push_line(&format!(
                "pub {rust_name}: ::std::collections::BTreeMap<{key_type}, {val_type}>,"
            ));
            return Ok(());
        }

        let is_repeated = label == FieldLabel::Repeated;
        let is_optional = self.is_field_optional(field);
        let field_type = field.r#type.unwrap_or(FieldType::Int32);

        let base_type = self.rust_field_type_runtime(field);

        let full_type = if is_repeated {
            format!("::std::vec::Vec<{base_type}>")
        } else if field_type == FieldType::Message {
            // Message fields use MessageField<T>
            if is_optional || label == FieldLabel::Optional {
                format!("protoc_rs_runtime::MessageField<{base_type}>")
            } else {
                // Required message field (proto2)
                format!("protoc_rs_runtime::MessageField<{base_type}>")
            }
        } else if is_optional {
            format!("::core::option::Option<{base_type}>")
        } else {
            base_type
        };

        self.push_line(&format!("pub {rust_name}: {full_type},"));
        Ok(())
    }

    fn rust_field_type_runtime(&self, field: &FieldDescriptorProto) -> String {
        let ft = field.r#type.unwrap_or(FieldType::Int32);
        match ft {
            FieldType::Message => {
                let type_name = field.type_name.as_deref().unwrap_or("Unknown");
                fqn_to_rust_path(type_name, &self.current_fqn_prefix())
            }
            FieldType::Enum => {
                let type_name = field.type_name.as_deref().unwrap_or("Unknown");
                let rust_path = fqn_to_rust_path(type_name, &self.current_fqn_prefix());
                format!("protoc_rs_runtime::EnumValue<{rust_path}>")
            }
            _ => rust_scalar_type(ft).to_string(),
        }
    }

    fn is_field_optional(&self, field: &FieldDescriptorProto) -> bool {
        self.features.is_scalar_optional(field)
    }

