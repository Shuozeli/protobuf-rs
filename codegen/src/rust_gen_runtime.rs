    // -----------------------------------------------------------------------

    fn gen_compute_size(
        &mut self,
        regular_fields: &[&FieldDescriptorProto],
        oneof_groups: &[(i32, Vec<&FieldDescriptorProto>)],
        parent_msg: &DescriptorProto,
    ) -> Result<(), CodeGenError> {
        self.push_line("fn compute_size(&self) -> u32 {");
        self.indent += 1;
        self.push_line("let mut size = 0u32;");

        for field in regular_fields {
            self.gen_field_compute_size(field, parent_msg)?;
        }

        for (oneof_idx, fields) in oneof_groups {
            let oneof_decl = &parent_msg.oneof_decl[*oneof_idx as usize];
            let oneof_name = oneof_decl.name.as_deref().unwrap_or("unknown");
            let oneof_rust_name = to_snake(oneof_name);

            self.push_line(&format!("if let ::core::option::Option::Some(ref oneof) = self.{oneof_rust_name} {{"));
            self.indent += 1;
            self.push_line("match oneof {");
            self.indent += 1;

            let mod_name = to_snake(
                parent_msg
                    .name
                    .as_deref()
                    .unwrap_or("unknown"),
            );
            let oneof_type_name = to_upper_camel(oneof_name);

            for field in fields {
                let field_name = field.name.as_deref().unwrap_or("unknown");
                let variant_name = to_upper_camel(field_name);
                let tag = field.number.unwrap_or(0) as u32;
                let field_type = field.r#type.unwrap_or(FieldType::Int32);

                if field_type == FieldType::Message {
                    self.push_line(&format!(
                        "{mod_name}::{oneof_type_name}::{variant_name}(ref v) => {{",
                    ));
                    self.indent += 1;
                    // v is &Box<T>, deref to &T
                    self.push_line(&format!(
                        "size += protoc_rs_runtime::message::message_field_size({tag}, &**v);",
                    ));
                    self.indent -= 1;
                    self.push_line("}");
                } else {
                    self.push_line(&format!(
                        "{mod_name}::{oneof_type_name}::{variant_name}(ref v) => {{",
                    ));
                    self.indent += 1;
                    let tag_size = format!("protoc_rs_runtime::wire::varint_len((({tag}u64) << 3) | {})", wire_type_for_field_type(field_type));
                    let val_size = if field_type == FieldType::Enum {
                        "protoc_rs_runtime::wire::varint_len(v.to_i32() as u64)".to_string()
                    } else {
                        scalar_compute_size_expr("v", field_type)
                    };
                    self.push_line(&format!("size += ({tag_size} + {val_size}) as u32;"));
                    self.indent -= 1;
                    self.push_line("}");
                }
            }

            self.indent -= 1;
            self.push_line("}");
            self.indent -= 1;
            self.push_line("}");
        }

        self.push_line("size += self._unknown_fields.encoded_len() as u32;");
        self.push_line("self._cached_size.set(size);");
        self.push_line("size");
        self.indent -= 1;
        self.push_line("}");

        Ok(())
    }

    fn gen_field_compute_size(
        &mut self,
        field: &FieldDescriptorProto,
        parent_msg: &DescriptorProto,
    ) -> Result<(), CodeGenError> {
        let name = field.name.as_deref().unwrap_or("unknown");
        let rust_name = to_snake(name);
        let tag = field.number.unwrap_or(0) as u32;
        let label = field.label.unwrap_or(FieldLabel::Optional);
        let field_type = field.r#type.unwrap_or(FieldType::Int32);

        let tag_size_expr = format!(
            "protoc_rs_runtime::wire::varint_len((({tag}u64) << 3) | {})",
            wire_type_for_field_type(field_type)
        );

        // Map field
        if let Some((key_field, val_field)) = find_map_entry(field, parent_msg) {
            let key_type = key_field.r#type.unwrap_or(FieldType::Int32);
            let val_type = val_field.r#type.unwrap_or(FieldType::Int32);
            self.push_line(&format!(
                "for (k, v) in &self.{rust_name} {{"
            ));
            self.indent += 1;
            // Each map entry is a length-delimited message with field 1 = key, field 2 = value
            let key_tag_size = format!("protoc_rs_runtime::wire::varint_len(((1u64) << 3) | {})", wire_type_for_field_type(key_type));
            let val_tag_size = format!("protoc_rs_runtime::wire::varint_len(((2u64) << 3) | {})", wire_type_for_field_type(val_type));
            let key_val_size = scalar_compute_size_expr("k", key_type);
            let val_val_size = if val_type == FieldType::Message {
                "protoc_rs_runtime::message::message_field_size(2, v) as usize".to_string()
            } else if val_type == FieldType::Enum {
                scalar_compute_size_expr("&v.to_i32()", FieldType::Int32)
            } else {
                scalar_compute_size_expr("v", val_type)
            };

            if val_type == FieldType::Message {
                self.push_line(&format!(
                    "let entry_size = ({key_tag_size} + {key_val_size}) + {val_val_size};"
                ));
            } else {
                self.push_line(&format!(
                    "let entry_size = ({key_tag_size} + {key_val_size}) + ({val_tag_size} + {val_val_size});"
                ));
            }
            self.push_line(&format!(
                "size += ({tag_size_expr} + protoc_rs_runtime::wire::varint_len(entry_size as u64) + entry_size) as u32;"
            ));
            self.indent -= 1;
            self.push_line("}");
            return Ok(());
        }

        if label == FieldLabel::Repeated {
            let should_pack = self.features.is_packed(field);
            if should_pack && field_type != FieldType::Message && field_type != FieldType::Enum {
                // Packed encoding: tag + len_prefix + concatenated values
                self.push_line(&format!("if !self.{rust_name}.is_empty() {{"));
                self.indent += 1;
                let content_size = packed_content_size_expr(&rust_name, field_type);
                self.push_line(&format!("let content_len = {content_size};"));
                self.push_line(&format!(
                    "size += ({tag_size_expr} + protoc_rs_runtime::wire::varint_len(content_len as u64) + content_len) as u32;"
                ));
                self.indent -= 1;
                self.push_line("}");
            } else {
                // Unpacked: per-element tag + value
                self.push_line(&format!("for v in &self.{rust_name} {{"));
                self.indent += 1;
                if field_type == FieldType::Message {
                    self.push_line(&format!(
                        "size += protoc_rs_runtime::message::message_field_size({tag}, v);"
                    ));
                } else if field_type == FieldType::Enum {
                    let val_size = scalar_compute_size_expr("&v.to_i32()", FieldType::Int32);
                    self.push_line(&format!("size += ({tag_size_expr} + {val_size}) as u32;"));
                } else {
                    let val_size = scalar_compute_size_expr("v", field_type);
                    self.push_line(&format!("size += ({tag_size_expr} + {val_size}) as u32;"));
                }
                self.indent -= 1;
                self.push_line("}");
            }
            return Ok(());
        }

        if field_type == FieldType::Message {
            self.push_line(&format!("if self.{rust_name}.is_set() {{"));
            self.indent += 1;
            self.push_line(&format!(
                "size += protoc_rs_runtime::message::message_field_size({tag}, &*self.{rust_name});"
            ));
            self.indent -= 1;
            self.push_line("}");
            return Ok(());
        }

        let is_optional = self.is_field_optional(field);
        if is_optional {
            self.push_line(&format!("if let ::core::option::Option::Some(ref v) = self.{rust_name} {{"));
            self.indent += 1;
            if field_type == FieldType::Enum {
                let val_size = scalar_compute_size_expr("&v.to_i32()", FieldType::Int32);
                self.push_line(&format!("size += ({tag_size_expr} + {val_size}) as u32;"));
            } else {
                let val_size = scalar_compute_size_expr("v", field_type);
                self.push_line(&format!("size += ({tag_size_expr} + {val_size}) as u32;"));
            }
            self.indent -= 1;
            self.push_line("}");
        } else {
            // Non-optional scalar: only emit if non-default
            let default_check = scalar_default_check(&rust_name, field_type);
            self.push_line(&format!("if {default_check} {{"));
            self.indent += 1;
            if field_type == FieldType::Enum {
                let val_size = scalar_compute_size_expr(&format!("&self.{rust_name}.to_i32()"), FieldType::Int32);
                self.push_line(&format!("size += ({tag_size_expr} + {val_size}) as u32;"));
            } else {
                let val_size = scalar_compute_size_expr(&format!("&self.{rust_name}"), field_type);
                self.push_line(&format!("size += ({tag_size_expr} + {val_size}) as u32;"));
            }
            self.indent -= 1;
            self.push_line("}");
        }

        Ok(())
    }

