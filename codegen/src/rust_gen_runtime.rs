fn to_snake(name: &str) -> String {
    let s = name.to_snake_case();
    sanitize_keyword(&s)
}

fn to_upper_camel(name: &str) -> String {
    let s = name.to_upper_camel_case();
    if s.is_empty() {
        "Unknown".to_string()
    } else if s.starts_with(|c: char| c.is_ascii_digit()) {
        format!("_{s}")
    } else {
        s
    }
}

fn sanitize_keyword(name: &str) -> String {
    match name {
        "self" | "super" => format!("{name}_"),
        "as" | "break" | "const" | "continue" | "crate" | "else" | "enum" | "extern" | "false"
        | "fn" | "for" | "if" | "impl" | "in" | "let" | "loop" | "match" | "mod" | "move"
        | "mut" | "pub" | "ref" | "return" | "Self" | "static" | "struct" | "trait" | "true"
        | "type" | "unsafe" | "use" | "where" | "while" | "async" | "await" | "dyn"
        | "abstract" | "become" | "box" | "do" | "final" | "macro" | "override" | "priv"
        | "typeof" | "unsized" | "virtual" | "yield" | "try" => {
            format!("r#{name}")
        }
        _ => name.to_string(),
    }
}

fn strip_enum_prefix(enum_name: &str, value_name: &str) -> String {
    let prefix = enum_name.to_snake_case().to_uppercase();
    let stripped = if let Some(rest) = value_name.strip_prefix(&prefix) {
        if let Some(without_underscore) = rest.strip_prefix('_') {
            without_underscore
        } else {
            value_name
        }
    } else {
        value_name
    };
    if stripped.is_empty() {
        value_name.to_string()
    } else {
        stripped.to_string()
    }
}

fn fqn_to_rust_path(fqn: &str, current_scope: &str) -> String {
    crate::rust_gen::fqn_to_rust_path(fqn, current_scope)
}

