    // Message trait impl
    // -----------------------------------------------------------------------

    fn gen_message_impl(
        &mut self,
        rust_name: &str,
        msg: &DescriptorProto,
        regular_fields: &[&FieldDescriptorProto],
        oneof_groups: &[(i32, Vec<&FieldDescriptorProto>)],
    ) -> Result<(), CodeGenError> {
        let full_name = if self.package.is_empty() {
            rust_name.to_string()
        } else {
            format!("{}.{}", self.package, rust_name)
        };

        self.push_line(&format!("impl protoc_rs_runtime::Message for {rust_name} {{"));
        self.indent += 1;

        // --- compute_size ---
        self.gen_compute_size(regular_fields, oneof_groups, msg)?;

        // --- write_to ---
        self.gen_write_to(regular_fields, oneof_groups, msg)?;

        // --- merge_field ---
        self.gen_merge_field(regular_fields, oneof_groups, msg)?;

        // --- clear ---
        self.gen_clear(regular_fields, oneof_groups, msg)?;

        // --- cached_size ---
        self.push_line("fn cached_size(&self) -> &protoc_rs_runtime::CachedSize {");
        self.indent += 1;
        self.push_line("&self._cached_size");
        self.indent -= 1;
        self.push_line("}");

        // --- unknown_fields ---
        self.push_line("fn unknown_fields(&self) -> &protoc_rs_runtime::UnknownFields {");
        self.indent += 1;
        self.push_line("&self._unknown_fields");
        self.indent -= 1;
        self.push_line("}");

        self.push_line("fn unknown_fields_mut(&mut self) -> &mut protoc_rs_runtime::UnknownFields {");
        self.indent += 1;
        self.push_line("&mut self._unknown_fields");
        self.indent -= 1;
        self.push_line("}");

        // --- full_name ---
        self.push_line("fn full_name() -> &'static str {");
        self.indent += 1;
        self.push_line(&format!("\"{full_name}\""));
        self.indent -= 1;
        self.push_line("}");

        self.indent -= 1;
        self.push_line("}");

        Ok(())
    }

