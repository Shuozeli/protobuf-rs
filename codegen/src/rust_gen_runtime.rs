    fn field_default_value(
        &self,
        field: &FieldDescriptorProto,
        parent_msg: &DescriptorProto,
    ) -> String {
        let label = field.label.unwrap_or(FieldLabel::Optional);
        let field_type = field.r#type.unwrap_or(FieldType::Int32);

        if find_map_entry(field, parent_msg).is_some() {
            return "::std::collections::BTreeMap::new()".to_string();
        }

        if label == FieldLabel::Repeated {
            return "::std::vec::Vec::new()".to_string();
        }

        if field_type == FieldType::Message {
            return "protoc_rs_runtime::MessageField::none()".to_string();
        }

        let is_optional = self.is_field_optional(field);
        if is_optional {
            return "::core::option::Option::None".to_string();
        }

        // Check for proto2 custom default value
        if let Some(ref default_str) = field.default_value {
            return match field_type {
                FieldType::Bool => default_str.clone(), // "true" or "false"
                FieldType::String => format!("::std::string::String::from({:?})", default_str),
                FieldType::Bytes => {
                    // Proto default bytes are C-escaped strings
                    format!("::std::vec::Vec::from({:?}.as_bytes())", default_str)
                }
                FieldType::Float => format!("{default_str}f32"),
                FieldType::Double => format!("{default_str}f64"),
                FieldType::Enum => {
                    // default_value is the enum variant name, need to look it up
                    let type_name = field.type_name.as_deref().unwrap_or("Unknown");
                    let rust_path = fqn_to_rust_path(type_name, &self.current_fqn_prefix());
                    let variant = to_upper_camel(default_str);
                    format!("protoc_rs_runtime::EnumValue::Known({rust_path}::{variant})")
                }
                FieldType::Sint32 | FieldType::Sfixed32 | FieldType::Int32 => {
                    format!("{default_str}i32")
                }
                FieldType::Sint64 | FieldType::Sfixed64 | FieldType::Int64 => {
                    format!("{default_str}i64")
                }
                FieldType::Uint32 | FieldType::Fixed32 => format!("{default_str}u32"),
                FieldType::Uint64 | FieldType::Fixed64 => format!("{default_str}u64"),
                _ => default_str.clone(),
            };
        }

        match field_type {
            FieldType::Enum => "protoc_rs_runtime::EnumValue::default()".to_string(),
            FieldType::Bool => "false".to_string(),
            FieldType::String => "::std::string::String::new()".to_string(),
            FieldType::Bytes => "::std::vec::Vec::new()".to_string(),
            FieldType::Float | FieldType::Double => "0.0".to_string(),
            _ => "0".to_string(),
        }
    }

