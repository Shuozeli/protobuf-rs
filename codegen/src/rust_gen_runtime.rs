    fn test_view_types_generated() {
        let fds = FileDescriptorSet {
            file: vec![FileDescriptorProto {
                name: Some("test.proto".to_string()),
                package: Some("test".to_string()),
                syntax: Some("proto3".to_string()),
                message_type: vec![DescriptorProto {
                    name: Some("Person".to_string()),
                    field: vec![
                        FieldDescriptorProto {
                            name: Some("name".to_string()),
                            number: Some(1),
                            label: Some(FieldLabel::Optional),
                            r#type: Some(FieldType::String),
                            ..Default::default()
                        },
                        FieldDescriptorProto {
                            name: Some("id".to_string()),
                            number: Some(2),
                            label: Some(FieldLabel::Optional),
                            r#type: Some(FieldType::Int32),
                            ..Default::default()
                        },
                        FieldDescriptorProto {
                            name: Some("data".to_string()),
                            number: Some(3),
                            label: Some(FieldLabel::Optional),
                            r#type: Some(FieldType::Bytes),
                            ..Default::default()
                        },
                    ],
                    ..Default::default()
                }],
                ..Default::default()
            }],
        };

        let source = gen_source(&fds);

        // View struct uses borrowed types
        assert!(source.contains("pub struct PersonView<'a>"));
        assert!(source.contains("pub name: &'a str,"));
        assert!(source.contains("pub data: &'a [u8],"));
        assert!(source.contains("pub id: i32,")); // scalars stay owned

        // Implements MessageView
        assert!(source.contains("impl<'a> protoc_rs_runtime::view::MessageView<'a> for PersonView<'a>"));

        // PhantomData for unused lifetime
        assert!(source.contains("PhantomData"));
    }
