/// Rust type for a scalar field in a view (borrows for string/bytes).
fn view_scalar_type(ft: FieldType) -> &'static str {
    match ft {
        FieldType::Double => "f64",
        FieldType::Float => "f32",
        FieldType::Int64 | FieldType::Sfixed64 | FieldType::Sint64 => "i64",
        FieldType::Uint64 | FieldType::Fixed64 => "u64",
        FieldType::Int32 | FieldType::Sfixed32 | FieldType::Sint32 | FieldType::Enum => "i32",
        FieldType::Uint32 | FieldType::Fixed32 => "u32",
        FieldType::Bool => "bool",
        FieldType::String => "&'a str",
        FieldType::Bytes => "&'a [u8]",
        FieldType::Message | FieldType::Group => "Unknown",
    }
}

/// Decode expression for a scalar in a view (borrows for string/bytes).
fn view_scalar_decode_expr(ft: FieldType) -> String {
    match ft {
        FieldType::String => {
            concat!(
                "let (len, header) = protoc_rs_runtime::wire::decode_varint(buf)?;\n",
                "let end = header + len as usize;\n",
                "if end > buf.len() { return ::core::result::Result::Err(protoc_rs_runtime::DecodeError::UnexpectedEof); }\n",
                "let val: &str = std::str::from_utf8(&buf[header..end]).map_err(|_| protoc_rs_runtime::DecodeError::InvalidUtf8)?;\n",
                "let consumed = end;"
            ).to_string()
        }
        FieldType::Bytes => {
            concat!(
                "let (len, header) = protoc_rs_runtime::wire::decode_varint(buf)?;\n",
                "let end = header + len as usize;\n",
                "if end > buf.len() { return ::core::result::Result::Err(protoc_rs_runtime::DecodeError::UnexpectedEof); }\n",
                "let val: &[u8] = &buf[header..end];\n",
                "let consumed = end;"
            ).to_string()
        }
        // All other scalars are identical to owned decode
        _ => scalar_decode_expr(ft),
    }
}

